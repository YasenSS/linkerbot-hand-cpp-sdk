    std::vector<uint8_t> hex_bytes(const std::string &text) {
        std::vector<uint8_t> out;
        for (size_t i = 0; i < text.size(); i += 2) {
            out.push_back(static_cast<uint8_t>(std::stoul(text.substr(i, 2), nullptr, 16)));
        }
        return out;
    }

    void modern(o30_comm::Harness &h) { h.hop->put_ascii(0x41, 0x61, 8, "0.0.4"); }

